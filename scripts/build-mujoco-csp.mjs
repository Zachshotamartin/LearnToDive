import { readFile, writeFile, mkdir } from 'node:fs/promises';
import { createHash } from 'node:crypto';
import { fileURLToPath } from 'node:url';
import { dirname, resolve } from 'node:path';

// Deliberately fail closed on a dependency update. Review the upstream glue and
// regenerate after checking its complete source hash; never patch unknown code.
const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const expectedJs = 'cb6752b9eab4f4cf9eac57911b58fea48cb808f323a563674f051935794fccdb';
const expectedWasm = '41dce8820addd75f9d4f6cbb11ff136ecdbaaa29541db4c323ce2d9e4c8a7661';
const hash = data => createHash('sha256').update(data).digest('hex');
const original = await readFile(resolve(root, 'node_modules/@mujoco/mujoco/mujoco.js'), 'utf8');
const wasm = await readFile(resolve(root, 'node_modules/@mujoco/mujoco/mujoco.wasm'));
if (hash(original) !== expectedJs || hash(wasm) !== expectedWasm) {
  throw new Error('Unreviewed MuJoCo glue or WASM version: CSP generation refused.');
}
let output = original;
function replaceSection(start, end, replacement) {
  const first = output.indexOf(start), last = output.indexOf(end, first + start.length);
  if (first < 0 || last < 0 || output.indexOf(start, first + 1) >= 0) {
    throw new Error(`Expected exactly one complete source section: ${start}`);
  }
  output = output.slice(0, first) + replacement.trimEnd() + '\n  \n' + output.slice(last);
}
replaceSection('  function createJsInvoker(', '  function getRequiredArgCount(', '');
replaceSection('  function craftInvokerFunction(', '  var heap32VectorToArray =',
  await readFile(resolve(root, 'scripts/vendor/embind-csp.js.txt'), 'utf8'));
replaceSection('  var __emval_get_method_caller =', '  var __emval_get_property =',
  await readFile(resolve(root, 'scripts/vendor/emval-csp.js.txt'), 'utf8'));
if (/\bnew\s+Function\b|\beval\s*\(/.test(output)) {
  throw new Error('Generated glue still contains dynamic JavaScript compilation.');
}
output = `/* MuJoCo 3.13.0: generated CSP-compatible JS glue.
 * Generate with node scripts/build-mujoco-csp.mjs. Do not edit this file.
 * Upstream JS SHA256 ${expectedJs}
 * Unmodified WASM SHA256 ${expectedWasm}
 * Two invokers adapted from Emscripten DYNAMIC_EXECUTION=0. See README.md and
 * EMSCRIPTEN-LICENSE.txt / MUJOCO-LICENSE.txt in this directory.
 */\n` + output;
const destination = resolve(root, 'src/vendor/mujoco-csp.js');
if (process.argv.includes('--check')) {
  if (await readFile(destination, 'utf8') !== output) throw new Error('CSP glue is stale; regenerate it.');
} else {
  await mkdir(dirname(destination), { recursive: true });
  await writeFile(destination, output);
}
console.log(`CSP glue verified: ${hash(output)}; WASM unchanged: ${expectedWasm}`);
